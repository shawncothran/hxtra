"""Label color: HXtra settings' and block parameters' labels in Teal, so they read apart from the stock white ones (src/m4/label_color.s)."""
import struct

import patch_amp as pa
import patch_menu as pm
from features import tap_color
from setting_ids import VIRTUAL_IDS

FLAG = 'HX_LABEL_COLOR'
XL_PORTED = True
ORDER = -1                          # before tuner, whose page paint colours its labels with label_any
MODULE = 'src/m4/label_color.s'
TEAL = tap_color.TEXTS[5]

# The section paint 0x28dce854's 0x28dc6454(slot, white), with the slot's setting ID in r5
LABEL_CALL, LABEL_COLOUR = 0x28dce962, 0x28dc6454
# The Edit view's parameter knob drawer 0x28dbf5c4's 0x28dc63d0(knob, name), its block info in r5
PARAM_CALL, PARAM_LABEL = 0x28dbf800, 0x28dc63d0
NAM, METRONOME = 'HD2_DistNAMLite', 181     # patch_click.PRESET_ID: added after this step, so not in Table 1 yet


def hxtra_params(e0_read, e0_u32, segs, e3):
    """[(preset ID, first HXtra parameter index)]: GR knobs after each compressor's own; all of NAM's and the Metronome's."""
    import patch_comp
    A = pa.e0_device(segs)
    tab1 = e0_u32(A.TAB1_BASE_PTRS[0])
    _, n = pa._decode_thumb_movw(e0_read(A.TAB1_CNT_INSN, 4))
    pid = {}
    for i in range(n):
        name_idx, preset_id, _, _ = struct.unpack('<IHHI', e0_read(tab1 + 12 * i, 12))
        pid[name_idx] = preset_id
    models = {m['name']: m for m in pa.parse_entry3_full(e3)['models']}
    out = [(pid[models[name]['words'][2]], len(models[name]['params'])) for name, _ in patch_comp.COMP_MODELS]
    if NAM in models and models[NAM]['words'][2] in pid:
        out.append((pid[models[NAM]['words'][2]], 0))
    if METRONOME not in pid.values():
        out.append((METRONOME, 0))
    return out


def label_inc(params, label_colour=LABEL_COLOUR, label_text=PARAM_LABEL):
    table = '\n'.join(f'    .hword {pid}\n    .byte {first}, 0' for pid, first in params)
    return (f'@ label.inc - generated by tools/features/label_color.py\n.equ VIRTUAL_FIRST, {VIRTUAL_IDS.start:#x}\n'
            f'.equ VIRTUAL_COUNT, {len(VIRTUAL_IDS)}\n.equ TEAL, {TEAL:#08x}\n'
            f'.equ LABEL_COLOUR, {label_colour | 1:#x}\n.equ LABEL_TEXT, {label_text | 1:#x}\n'
            f'.equ PARAMS, {len(params)}\n.macro PARAM_TABLE\n{table}\n.endm\n')


def apply(p):
    xl = getattr(p, 'layout', pm.STOMP_MENU).base == pm.XL_MENU.base
    label_call, label_colour = (0x28dd4412, 0x28dc9594) if xl else (LABEL_CALL, LABEL_COLOUR)
    param_call, param_label = (0x28dc28f0, 0x28dc9510) if xl else (PARAM_CALL, PARAM_LABEL)
    params = hxtra_params(p.read, p.u32, p.segs, p.entry(3).read(0, len(p.entry(3).data)))
    m = p.module(MODULE, inc={'label.inc': label_inc(params, label_colour, param_label)})
    p.own_call(label_call, label_colour, 'the Global Settings label colour', m['label_colour'])
    p.own_call(param_call, param_label, 'the Edit view parameter label', m['label_param'])
